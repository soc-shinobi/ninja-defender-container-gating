#!/usr/bin/env bash
# Deploy the Defender for Cloud demo lab. Idempotent; safe to re-run.
set -euo pipefail

LOCATION="${LOCATION:-swedencentral}"
NAME_PREFIX="${NAME_PREFIX:-defdemo}"
# Resource group. main.bicepparam reads the same RG variable, and so does every
# other script here, so one export covers deploy, park/start, auth and destroy.
export RG="${RG:-rg-${NAME_PREFIX}}"
# Defender sensor: Helm by default. main.bicepparam reads the same variable to tag the cluster
# out of sensor auto-provisioning and disable the add-on; this script installs the chart below.
export DEFENDER_SENSOR_VIA_HELM="${DEFENDER_SENSOR_VIA_HELM:-true}"
DEPLOY_NAME="defdemo-$(date +%Y%m%d-%H%M%S)"
SECRETS_FILE=".deploy-secrets.env"

echo ">> Subscription:"
az account show --query "{name:name, id:id}" -o table

# CLI extensions (containerapp, k8s-configuration) + resource providers. Idempotent.
bash "$(dirname "$0")/az-prereqs.sh"

# Auto-fill your object ID; the bicepparam reads it via ADMIN_PRINCIPAL_ID.
# (A .bicepparam file cannot be reliably combined with inline --parameters, so we
# pass this through the environment instead.)
export ADMIN_PRINCIPAL_ID="${ADMIN_PRINCIPAL_ID:-$(az ad signed-in-user show --query id -o tsv 2>/dev/null || echo '')}"

# Repo URL for Flux (only used when deployFlux=true). ssh remotes are converted to https.
if [[ -z "${GIT_REPO_URL:-}" ]]; then
  ORIGIN="$(git remote get-url origin 2>/dev/null || true)"
  GIT_REPO_URL="$(printf '%s' "$ORIGIN" | sed -E 's#^git@github\.com:#https://github.com/#; s#\.git$##')"
fi
export GIT_REPO_URL

if [[ "${DEPLOY_FLUX:-true}" == "true" && -z "$GIT_REPO_URL" ]]; then
  echo "DEPLOY_FLUX=true requires a reachable GIT_REPO_URL or git origin." >&2
  exit 1
fi

# A parked (stopped) cluster, or one still mid-operation (Starting, Stopping, Updating,
# Upgrading...), rejects every ARM write with OperationNotAllowed deep inside the nested
# deployment. Fail fast with the fix instead. Empty = no cluster yet (first deploy).
# Failed provisioning is let through: a fresh PUT is what reconciles it.
read -r AKS_POWER_STATE AKS_PROV_STATE < <(az aks show -g "$RG" -n "${NAME_PREFIX}-aks" \
  --query "[powerState.code, provisioningState]" -o tsv 2>/dev/null | paste -sd ' ') || true
if [[ -n "${AKS_POWER_STATE:-}" ]]; then
  if [[ "$AKS_POWER_STATE" != "Running" ]]; then
    echo "AKS $RG/${NAME_PREFIX}-aks is $AKS_POWER_STATE, not Running; ARM cannot update a stopped cluster." >&2
    echo "Start it first: RG=$RG NAME_PREFIX=$NAME_PREFIX bash scripts/lab-start.sh  (or: make lab-start)" >&2
    exit 1
  fi
  if [[ "$AKS_PROV_STATE" != "Succeeded" && "$AKS_PROV_STATE" != "Failed" ]]; then
    echo "AKS $RG/${NAME_PREFIX}-aks has an operation in progress (provisioningState: $AKS_PROV_STATE); ARM cannot update it until that finishes." >&2
    echo "Wait for Succeeded, then re-run: az aks wait -g $RG -n ${NAME_PREFIX}-aks --updated --interval 30" >&2
    exit 1
  fi
  [[ "$AKS_PROV_STATE" == "Failed" ]] && echo "!! AKS provisioningState is Failed; this deploy will try to reconcile it." >&2
fi

# Reuse generated credentials across idempotent retries instead of silently rotating them.
if [[ -f "$SECRETS_FILE" ]]; then
  # Values generated by this script are strictly alphanumeric.
  source "$SECRETS_FILE"
fi

# ---- who may open the control panel -------------------------------------
# PANEL_ENTRA_USER set -> Entra EasyAuth scoped to that user (run `make auth` after).
# unset              -> the app enforces HTTP Basic with a random password generated here.
export PANEL_ENTRA_USER="${PANEL_ENTRA_USER:-}"
if [[ -z "$PANEL_ENTRA_USER" && -z "${PANEL_BASIC_PASSWORD:-}" ]]; then
  # No pipe into head: `head -c` closes early, tr dies on SIGPIPE and `set -o pipefail`
  # would abort the whole deployment here. Read a fixed slice, then trim in bash.
  PANEL_RANDOM="$(LC_ALL=C tr -dc 'A-Za-z0-9' < <(head -c 512 /dev/urandom))"
  PANEL_BASIC_PASSWORD="${PANEL_RANDOM:0:28}"
  GENERATED_BASIC=1
fi
export PANEL_BASIC_PASSWORD="${PANEL_BASIC_PASSWORD:-}"

# ---- machine access to the REST API -------------------------------------
# Scripts and agents authenticate with a key header instead of Basic. The key is a Container
# App secret; generated here when unset, printed once, never written to git.
export PANEL_BASIC_USER="${PANEL_BASIC_USER:-panel}"
if [[ -z "${PANEL_API_KEY:-}" ]]; then
  API_RANDOM="$(LC_ALL=C tr -dc 'A-Za-z0-9' < <(head -c 512 /dev/urandom))"
  PANEL_API_KEY="${API_RANDOM:0:40}"
  GENERATED_API_KEY=1
fi
export PANEL_API_KEY

if [[ ! -f "$SECRETS_FILE" ]]; then
  umask 077
  {
    printf 'PANEL_BASIC_PASSWORD=%s\n' "$PANEL_BASIC_PASSWORD"
    printf 'PANEL_API_KEY=%s\n' "$PANEL_API_KEY"
  } > "$SECRETS_FILE"
  chmod 600 "$SECRETS_FILE"
fi

# ---- ACA egress lockdown (opt-in, default off) ---------------------------
# ENABLE_ACA_VNET=true puts the Container Apps environment in a VNet whose subnet carries a
# deny-all egress NSG. Costs ~$26/month (managed load balancer + 2 public IPs) and CANNOT be
# flipped on an existing environment. See ACA-readme.md.
export ENABLE_ACA_VNET="${ENABLE_ACA_VNET:-false}"
export AKS_API_SERVER_IP="${AKS_API_SERVER_IP:-}"
if [[ "$ENABLE_ACA_VNET" != "true" && "$ENABLE_ACA_VNET" != "false" ]]; then
  echo "ENABLE_ACA_VNET must be exactly 'true' or 'false' (got: '$ENABLE_ACA_VNET')" >&2
  exit 1
fi
# ---- parallel phases ------------------------------------------------------
# The slow parts do not depend on each other, so they overlap instead of queueing:
#   images  build + push as soon as the ACR exists, while AKS is still provisioning
#   flux    the Flux extension (~6 min) deploys on its own, alongside the post-deploy steps
# Logs of the background jobs land in .build-images.log and .flux-deploy.log.
export FLUX_SEPARATE_DEPLOYMENT=true
GIT_SHA="$(git rev-parse --short HEAD 2>/dev/null || echo nogit)"
export BUILD_TAG="${BUILD_TAG:-${GIT_SHA}-$(date -u +%Y%m%d%H%M%S)}"
IMAGES_PID=""
if [[ "${AUTO_BUILD_APP:-true}" == "true" ]]; then
  (
    for _ in $(seq 1 90); do
      ACR_NAME="$(az acr list -g "$RG" --query "[?provisioningState=='Succeeded'] | [0].name" -o tsv 2>/dev/null || true)"
      [[ -n "$ACR_NAME" ]] && break
      sleep 10
    done
    [[ -n "$ACR_NAME" ]] || { echo "no ACR in $RG after 15 min" >&2; exit 1; }
    ACR_NAME="$ACR_NAME" BUILD_PHASE=images bash scripts/build-push-app.sh
  ) > .build-images.log 2>&1 &
  IMAGES_PID=$!
  echo ">> Building images in the background (tag $BUILD_TAG, log .build-images.log)"
fi

# wait_job <pid> <label> <log>: wait for a background phase; on failure show its log and stop.
wait_job() {
  local rc=0
  wait "$1" || rc=$?
  if (( rc != 0 )); then
    echo "!! $2 failed (exit $rc). Last lines of $3:" >&2
    tail -n 40 "$3" >&2
    exit "$rc"
  fi
  echo ">> $2 done"
}

echo ">> Resource group: $RG   location: $LOCATION"
echo ">> Deploying (subscription scope)... admin principal: ${ADMIN_PRINCIPAL_ID:-<none>}  repo: ${GIT_REPO_URL:-<none, Flux off>}"
set +e
az deployment sub create \
  --name "$DEPLOY_NAME" \
  --location "$LOCATION" \
  --parameters infra/main.bicepparam \
  --query "properties.outputs" -o json \
  2> >(tee .last-deploy-error.log >&2) | tee ./.last-outputs.json
DEPLOY_RC=${PIPESTATUS[0]}
set -e

if (( DEPLOY_RC != 0 )); then
  # Subscription errors often wrap the useful nested ACA error. Add the workload error so
  # capacity fallback detection sees the actual provider code.
  az deployment group show -g "$RG" -n workload --query properties.error -o json \
    >> .last-deploy-error.log 2>/dev/null || true
  if grep -Eq 'ManagedEnvironmentNoAvailableCapacityInRegion|NoAvailableCapacityInRegion' .last-deploy-error.log; then
    FALLBACK_LOCATION="${ACA_FALLBACK_LOCATION:-norwayeast}"
    FALLBACK_ENV="${ACA_FALLBACK_ENV_NAME:-${NAME_PREFIX}-aca-env-noe}"
    echo ">> ACA capacity unavailable in ${ACA_LOCATION:-$LOCATION}; deploying only ACA in $FALLBACK_LOCATION"
    ACA_LOCATION="$FALLBACK_LOCATION" ACA_ENV_NAME="$FALLBACK_ENV" bash scripts/deploy-aca.sh
  else
    echo "Deployment failed for a non-capacity reason; no regional fallback attempted." >&2
    exit "$DEPLOY_RC"
  fi
fi

# Complete the runnable lab, not merely the ARM resources.
export ACR_NAME="${ACR_NAME:-$(az acr list -g "$RG" --query '[0].name' -o tsv)}"
export ACR_LOGIN_SERVER="$(az acr show -n "$ACR_NAME" --query loginServer -o tsv)"
export NAME_PREFIX

FLUX_PID=""
if [[ "${DEPLOY_FLUX:-true}" == "true" ]]; then
  # Same module and parameters the main deployment used to deploy; the PAT goes through a
  # private parameters file, never the command line.
  FLUX_PARAMS="$(mktemp)"
  chmod 600 "$FLUX_PARAMS"
  python3 - "$FLUX_PARAMS" <<'PY'
import json, os, sys
v = lambda k, d="": {"value": os.environ.get(k, d)}
json.dump({"$schema": "https://schema.management.azure.com/schemas/2019-04-01/deploymentParameters.json#",
           "contentVersion": "1.0.0.0",
           "parameters": {"aksName": {"value": os.environ["NAME_PREFIX"] + "-aks"},
                          "gitRepoUrl": v("GIT_REPO_URL"), "gitBranch": v("GIT_BRANCH", "main"),
                          "gitRepoToken": v("FLUX_GITHUB_TOKEN"),
                          "acrLoginServer": {"value": os.environ["ACR_LOGIN_SERVER"]}}},
          open(sys.argv[1], "w"))
PY
  (
    trap 'rm -f "$FLUX_PARAMS"' EXIT
    az deployment group create -g "$RG" -n flux -f infra/modules/flux.bicep \
      --parameters "@$FLUX_PARAMS" -o none
  ) > .flux-deploy.log 2>&1 &
  FLUX_PID=$!
  echo ">> Deploying Flux in the background (log .flux-deploy.log)"
fi

if [[ -n "$IMAGES_PID" ]]; then
  wait_job "$IMAGES_PID" "image build + push" .build-images.log
  BUILD_PHASE=panel bash scripts/build-push-app.sh
fi
bash infra/postdeploy/grant-controlpanel-access.sh
if [[ "$DEFENDER_SENSOR_VIA_HELM" == "true" ]]; then
  # The cluster carries ms_defender_container_exclude_sensors=true from the Bicep, so Defender
  # never auto-provisions the add-on next to this chart.
  AKS="${NAME_PREFIX}-aks" bash infra/postdeploy/install-defender-helm.sh
fi
# Gated deployment step 4, add-on sensor only. Without it the add-on admission controller cannot
# read ACR and admits everything. The Helm admission controller reads ACR as the kubelet
# identity, so with Helm the script finds gating off and skips. Never fails the deploy.
bash infra/postdeploy/attach-gating-identity.sh \
  || echo "! gating identity not attached - the image gate fails OPEN; run: make gating-identity"
bash infra/postdeploy/reconcile-azure-policy.sh
if [[ -n "$FLUX_PID" ]]; then
  wait_job "$FLUX_PID" "Flux deployment" .flux-deploy.log
  # The heartbeat targets the x-mdc-allowed workload, which Flux creates shortly after its
  # configuration lands. Give it up to five minutes.
  KC="$(mktemp)"
  az aks get-credentials -g "$RG" -n "${NAME_PREFIX}-aks" --admin --file "$KC" -o none
  for _ in $(seq 1 30); do
    kubectl --kubeconfig "$KC" -n x-mdc-allowed get deploy webapp -o name >/dev/null 2>&1 && break
    sleep 10
  done
  rm -f "$KC"
fi
if [[ "${DEPLOY_FLUX:-true}" != "true" ]]; then
  bash scripts/bootstrap-cluster.sh
fi
bash infra/postdeploy/configure-sensitive-storage.sh \
  || echo "! sensitive Blob connection not configured; run: make sensitive-storage"
bash infra/postdeploy/configure-heartbeat.sh || echo "! heartbeat not configured; run: make heartbeat"
bash scripts/verify-deployment.sh

echo ""
if [[ -n "$PANEL_ENTRA_USER" ]]; then
  printf '\033[1;36m>> Panel auth: ENTRA, scoped to %s\033[0m\n' "$PANEL_ENTRA_USER"
  echo "   Run:  make auth        (registers the app and assigns ONLY that user)"
else
  printf '\033[1;33m>> Panel auth: BASIC (no PANEL_ENTRA_USER given)\033[0m\n'
  if [[ -n "${GENERATED_BASIC:-}" ]]; then
    printf '   username: \033[1mpanel\033[0m\n   password: \033[1m%s\033[0m\n' "$PANEL_BASIC_PASSWORD"
    echo "   ^ shown ONCE. It is stored as a Container App secret, not in git."
  fi
  echo "   For Entra instead: PANEL_ENTRA_USER=<upn> make deploy && make auth"
fi
echo ""
printf '\033[1;36m>> REST API: key auth on /api/* (header X-API-Key)\033[0m\n'
if [[ -n "${GENERATED_API_KEY:-}" ]]; then
  printf '   X-API-Key: \033[1m%s\033[0m\n' "$PANEL_API_KEY"
  echo "   ^ shown ONCE. Stored as a Container App secret. Reuse it with PANEL_API_KEY=<key> make deploy."
else
  echo "   using the PANEL_API_KEY you supplied"
fi
echo "   curl -H \"X-API-Key: \$PANEL_API_KEY\" https://<panel-fqdn>/api/overview"
echo ""
if [[ "$ENABLE_ACA_VNET" == "true" ]]; then
  printf '\033[1;36m>> ACA network: VNET-INTEGRATED, egress NSG active\033[0m\n'
  if [[ -n "$AKS_API_SERVER_IP" ]]; then
    echo "   AKS API server pinned to $AKS_API_SERVER_IP - re-check it after every 'make start'."
  else
    echo "   AKS API server allowed via the regional AzureCloud tag (broad). Pin it with AKS_API_SERVER_IP."
  fi
  echo "   ~\$26/month for the managed load balancer + 2 public IPs. 'make park' does NOT stop this."
else
  printf '\033[1;90m>> ACA network: platform-managed (no egress NSG). ENABLE_ACA_VNET=true to lock it down.\033[0m\n'
fi
echo ""
echo ">> Deployment and readiness verification complete. Next steps:"
echo "   1. Configure gated rule + drift: infra/postdeploy/configure-gating-and-drift.sh"
echo "   2. Connect GitHub to Defender (manual OAuth): see README, 'GitHub connector'."
echo "   3. (optional) Publish the Foundry agent: infra/postdeploy/foundry-agent.sh"
